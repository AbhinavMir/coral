"""Write numbers.tex from results/*.json so the paper quotes run output, not typed values."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = ROOT / "results"


def cmd(name, value):
    return f"\\newcommand{{\\{name}}}{{{value}}}\n"


def n(x):
    return f"{x:,}"


def main():
    out = ["% generated by scripts/make_numbers.py; do not edit\n"]
    s = json.loads((R / "evaluate_sheet.json").read_text())
    out += [
        cmd("sheetLines", n(s["lines"])), cmd("sheetRows", n(s["lines"] + s["skipped"].get("no_billing_code", 0))),
        cmd("sheetNoCode", n(s["skipped"].get("no_billing_code", 0))),
        cmd("sheetRecords", n(s["records"])), cmd("sheetFixed", n(s["fixed"])), cmd("sheetPercent", n(s["percent"])),
        cmd("sheetAlgorithm", n(s["algorithm_only"])), cmd("sheetCollisions", n(s["key_collisions"])),
        cmd("sheetPayers", s["payers"]), cmd("sheetBatch", s["batch"]), cmd("sheetTx", n(s["transactions"])),
        cmd("sheetSignS", f"{s['sign_s']:.0f}"), cmd("sheetSigPerS", n(round(s["signatures_per_s"]))),
        cmd("sheetCommitS", n(round(s['commit_s']))), cmd("sheetCommitRun", n(s["committed_this_run"])),
        cmd("sheetCommitMin", f"{s['records']/s['records_per_s']/60:.1f}"),
        cmd("sheetRecPerS", n(round(s["records_per_s"]))),
        cmd("sheetGas", n(round(s["gas_per_record"]))), cmd("sheetBytes", n(round(s["calldata_bytes_per_record"]))),
        cmd("sheetCalldataMB", f"{s['calldata_bytes_total']/1e6:.0f}"),
        cmd("sheetDiskMB", n(round((s['validator_disk_bytes_after']-s['validator_disk_bytes_before'])/s['committed_this_run']*s['records']/1e6))),
        cmd("sheetDiskBytes", n(round((s['validator_disk_bytes_after']-s['validator_disk_bytes_before'])/s['committed_this_run']))),
        cmd("sheetLoadS", f"{s['index_load_s']:.0f}"), cmd("sheetVerifyLines", n(s["verify_lines"])),
        cmd("sheetVerifyS", f"{s['verify_s']:.1f}"), cmd("sheetLinesPerS", n(round(s["lines_per_s"]))),
        cmd("sheetCleanMatch", n(s["clean"].get("match", 0))), cmd("sheetCleanDiffers", n(s["clean"].get("amount_differs", 0))),
        cmd("sheetCleanOther", n(sum(v for k, v in s["clean"].items() if k not in ("match", "amount_differs")))),
        cmd("sheetAltered", n(s["altered"])), cmd("sheetCaught", n(s["caught"])),
        cmd("sheetAlreadyDiffers", n(s["altered_already_differs"])), cmd("sheetNotComparable", n(s["altered_not_comparable"])),
        cmd("sheetCleanNeedsCM", n(s["clean"].get("needs_chargemaster", 0))),
    ]
    # the body says no altered row that matched before the change matched after it
    assert s["altered_still_match"] == 0, s["altered_still_match"]
    assert s["caught"] + s["altered_already_differs"] + s["altered_not_comparable"] == s["altered"]
    # commit rate over the first 20,000 records of the run, from the progress log; the whole series goes to
    # results/commit_rate.dat (x = records on the ledger, y = records per second so far in the run)
    prog = [ln.split() for ln in (R / "evaluate_sheet.log").read_text().splitlines() if "committed," in ln]
    early = [ln for ln in prog if ln[0].startswith("20000/")]
    out.append(cmd("sheetRecPerSEarly", early[0][2]))
    # the log prints the cumulative average; the windowed rate over each 8-line span comes from the implied elapsed time
    pts = [(int(ln[0].split("/")[0]), float(ln[2])) for ln in prog]
    dat = ["ledger rate window\n"]
    for i, (cnt, avg) in enumerate(pts):
        win = "nan"
        if i >= 8:
            c0, a0 = pts[i - 8]
            win = f"{(cnt - c0) / (cnt / avg - c0 / a0):.0f}"
        dat.append(f"{s['already_on_ledger'] + cnt} {avg:.0f} {win}\n")
    (R / "commit_rate.dat").write_text("".join(dat))
    # rate over the last 50,000 records of the run, from the implied elapsed times of the cumulative averages
    (c1, a1) = pts[-1]
    (c0, a0) = next((c, a) for c, a in pts if c >= c1 - 50000)
    out.append(cmd("sheetRecPerSLate", n(round((c1 - c0) / (c1 / a1 - c0 / a0)))))
    out += [
        cmd("sheetAlready", n(s["already_on_ledger"])),
        cmd("sheetDiskBeforeGB", f"{s['validator_disk_bytes_before']/1e9:.2f}"),
        cmd("sheetRepeats", n(s["verify_lines"] - s["records"] - s["key_collisions"])),
    ]
    st = json.loads((R / "sheet_stats.json").read_text())
    assert st["rows_with_value"] == s["verify_lines"] and st["keys"] == s["records"]
    out += [
        cmd("sheetPctRows", n(st["percent_rows"])), cmd("sheetPctShare", f"{100*st['percent_rows']/st['rows_with_value']:.1f}"),
        cmd("sheetKeysMulti", n(st["keys_with_several_values"])), cmd("sheetRowsMulti", n(st["rows_on_those_keys"])),
    ]
    # projection to about 6,000 hospitals, each with a sheet of this size; the payer side is not counted
    H = 6000
    per_rec_disk = (s['validator_disk_bytes_after'] - s['validator_disk_bytes_before']) / s['committed_this_run']
    out += [
        cmd("projHospitals", n(H)), cmd("projRecordsB", f"{H*s['records']/1e9:.1f}"),
        cmd("projDiskTB", f"{H*s['records']*per_rec_disk/1e12:.0f}"),
        cmd("projCommitDays", n(round(H*s['records']/s['records_per_s']/86400))),
    ]
    p = json.loads((R / "evaluate_pairs.json").read_text())
    r = p["real"]
    a, al = r["all_providers"], r["all_providers_lines"]

    def pct(x, k):
        return f"{x[k]}" if x["comparable"] else "--"

    out += [
        cmd("pairProviders", len(p["providers"])), cmd("pairPayerLines", n(p["payer_lines"])),
        cmd("pairPayerUnique", n(p["payer_lines_unique"])), cmd("pairValuesPerKey", r["payer_values_per_paired_key"]),
        cmd("pairAll", n(a["pairs"])), cmd("pairComparable", n(a["comparable"])), cmd("pairNotComparable", n(a["not_comparable"])),
        cmd("pairExact", a["exact_pct"]), cmd("pairWithinTen", a["within_10_pct"]), cmd("pairOverFifty", a["over_50_pct"]),
        cmd("pairLineComparable", n(al["comparable"])), cmd("pairLineExact", al["exact_pct"]),
        cmd("pairLineAll", n(al["pairs"])), cmd("pairLineWithinTen", al["within_10_pct"]), cmd("pairLineOverFifty", al["over_50_pct"]),
        cmd("pairExactCount", round(a["exact_pct"] * a["comparable"] / 100)),
    ]
    # the same files paired on provider and code only (scripts/evaluate_pairs_coarse.py)
    c = json.loads((R / "evaluate_pairs_coarse.json").read_text())["all_providers"]
    out += [
        cmd("coarsePairs", n(c["pairs"])), cmd("coarseComparable", n(c["comparable"])), cmd("coarseNotComparable", n(c["not_comparable"])),
        cmd("coarseExact", c["exact_pct"]), cmd("coarseWithinTen", c["within_10_pct"]), cmd("coarseOverFifty", c["over_50_pct"]),
        cmd("coarseExactCount", round(c["exact_pct"] * c["comparable"] / 100)),
    ]
    # sensitivity of the pair run (scripts/pairs_sensitivity.py) and Wilson 95% intervals
    import math

    def wilson(k, nn, z=1.96):
        if not nn:
            return "--"
        ph = k / nn
        d = 1 + z * z / nn
        c0 = (ph + z * z / (2 * nn)) / d
        h = z * math.sqrt(ph * (1 - ph) / nn + z * z / (4 * nn * nn)) / d
        return f"{100*(c0-h):.0f}--{100*(c0+h):.0f}"

    sv = json.loads((R / "pairs_sensitivity.json").read_text())
    asa, dd, w5 = sv["b_with_asa"], sv["base_dedup"], sv["within_5_cents"]
    out += [
        cmd("sensAsaAllExact", asa["all_values"]["exact_pct"]), cmd("sensAsaAllWithin", asa["all_values"]["within_10_pct"]),
        cmd("sensAsaAllOver", asa["all_values"]["over_50_pct"]), cmd("sensAsaAllComparable", n(asa["all_values"]["comparable"])),
        cmd("sensAsaCoarseExact", asa["coarse"]["exact_pct"]), cmd("sensAsaCoarseOver", asa["coarse"]["over_50_pct"]),
        cmd("sensAsaCoarseComparable", n(asa["coarse"]["comparable"])),
        cmd("sensDedupAllExact", dd["all_values"]["exact_pct"]), cmd("sensDedupAllComparable", n(dd["all_values"]["comparable"])),
        cmd("pairWithinFiveCents", n(w5["all_values"])),
        cmd("pairLineExactCI", wilson(round(al["exact_pct"] * al["comparable"] / 100), al["comparable"])),
        cmd("coarseExactCI", wilson(round(c["exact_pct"] * c["comparable"] / 100), c["comparable"])),
    ]
    # block period observed in the run, from the first and last progress lines; projected signing time for the sheet
    blocks = int(prog[-1][-1]) - int(prog[0][-1])
    out += [
        cmd("sheetBlockS", f"{s['commit_s']/blocks:.1f}"),
        cmd("sheetSignMinSheet", f"{s['sign_s']*s['records']/s['committed_this_run']/60:.1f}"),
        cmd("sheetTotalMin", f"{(s['sign_s']*s['records']/s['committed_this_run'] + s['records']/s['records_per_s'])/60:.0f}"),
        cmd("pairLineExactCount", round(al["exact_pct"] * al["comparable"] / 100)),
    ]
    # the body letters the providers and does not name them; notes.tex keeps the mapping
    short = {"TIN:84-0398876": "A (Colorado)", "TIN:46-0796114": "B (Colorado)",
             "TIN:36-2169147": "C (Illinois)", "TIN:93-1176109": "D (Oregon)", "TIN:94-0562680": "E (California)"}
    rows = []
    for tin, m in p["providers"].items():
        m = dict(m, name=short.get(tin, m["name"]))
        x = r[tin]
        xl = x["lines"]
        rows.append(f"{m['name'].replace('&', chr(92) + '&')} & {m['dated']} & {m['codes_present']} & {x['provider_keys']} & {x['payer_keys_for_provider']} & "
                    f"{xl['pairs']} & {xl['comparable']} & {pct(xl, 'exact_pct')} & {pct(xl, 'within_10_pct')} & "
                    f"{pct(xl, 'over_50_pct')} \\\\")
    out.append("\\newcommand{\\pairRows}{" + "\n".join(rows) + "}\n")
    # per-provider counts for the bar chart: exact, within 10% but not exact, beyond 10%, not comparable
    bars = ["provider exact within beyond notcomp\n"]
    for tin, m in p["providers"].items():
        x, k = r[tin]["lines"], r[tin]["lines"]["comparable"]
        ex, wi = round(x["exact_pct"] * k / 100), round(x["within_10_pct"] * k / 100)
        bars.append(f"{short[tin].split()[0]} {ex} {wi - ex} {k - wi} {x['not_comparable']}\n")
    (R / "pairs_bars.dat").write_text("".join(bars))
    grows = []
    for g, label in (("inpatient", "Inpatient (8 MS-DRG)"), ("gi", "GI (5 CPT)"), ("ortho", "Orthopedic (3 CPT)")):
        agg = {"pairs": 0, "comparable": 0, "exact": 0, "within": 0, "over": 0}
        for tin in p["providers"]:
            x = r[tin]["groups"][g]
            agg["pairs"] += x["pairs"]
            agg["comparable"] += x["comparable"]
            agg["exact"] += x["exact_pct"] * x["comparable"] / 100
            agg["within"] += x["within_10_pct"] * x["comparable"] / 100
            agg["over"] += x["over_50_pct"] * x["comparable"] / 100
        k = agg["comparable"]
        pcts = f"{100*agg['exact']/k:.1f} & {100*agg['within']/k:.1f} & {100*agg['over']/k:.1f}" if k else "-- & -- & --"
        grows.append(f"{label} & {agg['pairs']} & {agg['comparable']} & {pcts} \\\\")
    out.append("\\newcommand{\\pairGroupRows}{" + "\n".join(grows) + "}\n")
    sy = p["synthetic"]
    t, res = sy["truth"], sy["result"]
    a = res["attribution"]
    out += [
        cmd("synKeys", n(sy["keys"])), cmd("synSigned", n(sy["records_signed"])),
        cmd("synProvAltered", n(t["provider_altered"])), cmd("synPayAltered", n(t["payer_altered"])), cmd("synBothAltered", n(t["both_altered"])),
        cmd("synExact", res["exact_pct"]), cmd("synWithinTen", res["within_10_pct"]),
        cmd("synBothMatch", n(a.get("both_match_record", 0))), cmd("synPayerDeparts", n(a.get("payer_file_departs", 0))),
        cmd("synProviderDeparts", n(a.get("provider_file_departs", 0))),
        cmd("synNeither", n(sum(v for k, v in a.items() if k not in ("both_match_record", "payer_file_departs", "provider_file_departs")))),
        cmd("synProvAlteredAll", n(t["provider_altered"] + t["both_altered"])),
        cmd("synPayAlteredAll", n(t["payer_altered"] + t["both_altered"])),
        cmd("synUnaltered", n(sy["keys"] - t["provider_altered"] - t["payer_altered"] - t["both_altered"])),
    ]
    assert a.get("both_match_record", 0) == sy["keys"] - t["provider_altered"] - t["payer_altered"] - t["both_altered"]
    (ROOT / "numbers.tex").write_text("".join(out))
    print("".join(out))


if __name__ == "__main__":
    main()
